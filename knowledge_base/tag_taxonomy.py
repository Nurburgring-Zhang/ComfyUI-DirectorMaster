def build_tag_tree():
    """构建完整三级标签树(供节点展示)"""
    tree = []
    for l1, l2_dict in TAG_TAXONOMY.items():
        l1_node = {"level": 1, "name": l1, "children": []}
        for l2, l3_list in l2_dict.items():
            l2_node = {"level": 2, "name": l2, "children": [{"level": 3, "name": x} for x in l3_list]}
            l1_node["children"].append(l2_node)
        tree.append(l1_node)
    return tree


def build_tag_display():
    """构建可视化标签树文本(节点UI展示)"""
    lines = ["【三级标签体系(豆瓣+平台真实分类)】"]
    for l1, l2_dict in TAG_TAXONOMY.items():
        lines.append(f"  L1 [{l1}]")
        for l2, l3_list in l2_dict.items():
            l3_str = "/".join(l3_list[:6]) + ("..." if len(l3_list) > 6 else "")
            lines.append(f"    L2 {l2}: {l3_str}")
    return "\n".join(lines)


def get_works_for_tag(l1, l2=None, l3=None):
    """按标签检索匹配作品(供节点标签筛选)"""
    # 简化: 返回该标签下作品的matchable_tags提示
    tags = []
    if l1: tags.append(l1)
    if l2: tags.append(l2)
    if l3: tags.append(l3)
    return tags


def taxonomy_stats():
    """标签体系统计"""
    l1_count = len(TAG_TAXONOMY)
    l2_count = sum(len(v) for v in TAG_TAXONOMY.values())
    l3_count = sum(len(l3) for v in TAG_TAXONOMY.values() for l3 in v.values())
    return {"L1": l1_count, "L2": l2_count, "L3": l3_count, "platforms": len(PLATFORM_TONE)}
