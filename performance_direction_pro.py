def detect_scene_archetype(scene_desc: str) -> str:
    """根据场景描述检测场景原型 (厨房/驾驶/婚礼/default)."""
    desc = scene_desc or ""
    if "厨房" in desc or "切菜" in desc or "灶" in desc:
        return "厨房"
    if "驾驶" in desc or "高速" in desc or "出租" in desc or "方向盘" in desc or "仪表" in desc:
        return "驾驶"
    if "婚礼" in desc or "新娘" in desc or "唢呐" in desc or "拜堂" in desc:
        return "婚礼"
    return "default"


