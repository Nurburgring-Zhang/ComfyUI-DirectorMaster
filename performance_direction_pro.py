def generate_body_words_block(director: str, intensity: float = 0.5) -> str:
    """
    动态生成 150 身体词块 (基础 100 + 导演 30 + 强度 20).

    参数:
        director:  导演名 (用于查 DIRECTOR_BODY_WORDS)
        intensity: 0.0-1.0 (用于查 INTENSITY_BODY_WORDS)

    返回:
        150 身体词渲染字符串
    """
    # 强度档
    if intensity < 0.3:
        level = "low"
    elif intensity < 0.7:
        level = "medium"
    elif intensity < 0.9:
        level = "high"
    else:
        level = "extreme"

    lines = []
    lines.append("【150 身体词动态生成 (5 维 × 20 词 + 导演 30 + 强度 20)】")
    lines.append("  强度档: " + level + " (" + str(round(intensity, 2)) + ")")
    lines.append("  导演: " + director)
    lines.append("")

    # 5 维 × 20 词
    for dim, words in BODY_VOCAB_150.items():
        lines.append("  [" + dim + " 维 (20 词)]")
        for w in words:
            lines.append("    - " + w)
        lines.append("")

    # 导演特定
    director_words = DIRECTOR_BODY_WORDS.get(director, DIRECTOR_BODY_WORDS["default"])
    lines.append("  [导演特定 (10 词): " + director + "]")
    for w in director_words:
        lines.append("    - " + w)
    lines.append("")

    # 强度特定
    intensity_words = INTENSITY_BODY_WORDS[level]
    lines.append("  [强度特定 (5 词): " + level + "]")
    for w in intensity_words:
        lines.append("    - " + w)

    return "\n".join(lines)


