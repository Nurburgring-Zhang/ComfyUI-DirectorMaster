def generate_au_block(emotion_category: str, intensity: float = 0.5) -> str:
    """
    动态生成 12 AU FACS 编码块 (Phase 35.9 真正实施).

    参数:
        emotion_category: 情感类别 (中英都支持, 模糊匹配)
        intensity:        情绪强度 0.0-1.0

    返回:
        至少 8 个 AU 编码的字符串 (强度 > 阈值才激活)
    """
    # 1) 匹配情感类别
    matched_key = None
    for key in EMOTION_AU_MAP:
        if key in emotion_category or emotion_category in key:
            matched_key = key
            break
    if not matched_key:
        matched_key = "压抑"  # 兜底

    primary_aus = EMOTION_AU_MAP[matched_key]

    # 2) 强度过滤: intensity < threshold 的 AU 不激活
    activated = []
    for au in primary_aus:
        threshold = FACS_AU_12[au]["intensity_threshold"]
        if intensity >= threshold:
            activated.append(au)

    # 3) 至少 8 个 AU (强度 < 0.3 时, 加上基础集)
    if len(activated) < 8:
        for au in ["AU1", "AU2", "AU4", "AU7", "AU12", "AU15", "AU17", "AU24"]:
            if au not in activated:
                activated.append(au)
            if len(activated) >= 8:
                break

    # 4) 渲染
    lines = []
    lines.append("【12 面部 AU 动态生成 (FACS 12 单元, 强度=" + str(round(intensity, 2)) + ")】")
    lines.append("  情感类别: " + emotion_category + " → 匹配 " + matched_key)
    lines.append("")
    lines.append("  激活的 AU (≥ 阈值):")
    for au in activated[:12]:
        info = FACS_AU_12[au]
        lines.append("    " + au + " (" + info["en"] + " / " + info["name"] +
                     ", 肌肉=" + info["muscle"] + ", 阈值=" + str(info["intensity_threshold"]) + ")")
    lines.append("")
    lines.append("  未激活的 AU (< 阈值):")
    inactive = [au for au in FACS_AU_12 if au not in activated]
    for au in inactive:
        info = FACS_AU_12[au]
        lines.append("    " + au + " (" + info["name"] + ", 阈值=" + str(info["intensity_threshold"]) + ")")
    return "\n".join(lines)


