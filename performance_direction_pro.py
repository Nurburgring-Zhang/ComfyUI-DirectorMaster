def _build_shot_seeds(scene_archetype: str, role_a: str, role_b: str,
                       prop1: str, prop2: str, prop3: str, prop4: str,
                       scene_5d: dict, director: str, intensity: float) -> list:
    """
    动态生成 5 Shot 身体动作 (按场景原型 × 导演 × 角色/道具 × 强度).

    返回: List of (label, body_lines)
    """
    templates = SCENE_SHOT_TEMPLATES.get(scene_archetype, SCENE_SHOT_TEMPLATES["default"])
    out = []
    for shot in templates:
        label = shot["label"]
        # 选场景模板 (按导演, fallback 到 default)
        body = shot["scenes"].get(director, shot["scenes"]["default"])
        # 强度调制: 极强度 (>0.9) 在每行末尾加"接近失控"标签
        if intensity >= 0.9:
            body = [line + " (强度 0.9+ 接近失控)" for line in body]
        # 替换角色名
        body = [line.replace("角色A", role_a).replace("角色B", role_b) for line in body]
        # 替换道具名
        body = [line.replace("道具1", prop1) for line in body]
        body = [line.replace("道具2", prop2) for line in body]
        body = [line.replace("道具3", prop3) for line in body]
        body = [line.replace("道具4", prop4) for line in body]
        out.append((label, body))
    return out




