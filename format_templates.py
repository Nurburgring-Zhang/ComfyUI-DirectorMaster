# 大师级影视语言升级（参考 Walter Murch《眨眼之间》、Roger Deakins、
# Thelma Schoonmaker 的剪辑理论）：
#   - 时长 = 叙事功能：定场给足呼吸，高潮快速切割，低谷留白沉思
