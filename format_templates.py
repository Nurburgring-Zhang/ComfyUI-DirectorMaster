#   - 转场 = 叙事语法：硬切=能量延续，叠化=时间流逝，淡出=章节终结
#
# 每个模板均确保输出中包含「时长 + 运镜 + 转场」三要素（按模态适配），
# 并在创作原则中加入大师级剪辑/构图/节奏的核心准则。
