ANTI_AI_REGEX_PATTERNS = [
    # 八股连接词
    (r"在这个.{0,10}中", "八股开场"),
    (r"让我们.{0,10}一起", "号召式套话"),
    (r"值得注意的是", "评论式插入"),
    (r"综上所述", "总结八股"),
    (r"首先.{0,20}其次", "列举八股"),
    (r"总而言之", "总结八股"),
    # 过度修饰
    (r"非常.{0,5}的", "过度修饰"),
    (r"极其.{0,5}的", "过度修饰"),
    (r"特别的.{0,5}的", "过度修饰"),
    # 安全选项 (回避决断)
    (r"也许.{0,10}可以", "回避决断"),
    (r"或许.{0,10}能够", "回避决断"),
    # 空洞升华
    (r"这不仅.{0,15}更是", "空洞升华"),
    (r"仿佛在诉说", "拟人套话"),
    (r"时光荏苒", "时间套话"),
    (r"命运的齿轮", "命运套话"),
]


def count_regex_hits(text):
    """统计正则套话命中. 返回 (总命中数, [(模式, 类别, 命中片段)])."""
    import re as _re_rx
    t = str(text or "")
    hits = []
    for pat, cat in ANTI_AI_REGEX_PATTERNS:
        for m in _re_rx.finditer(pat, t):
            hits.append((pat, cat, m.group(0)))
    return len(hits), hits


