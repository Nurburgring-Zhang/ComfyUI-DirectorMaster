def clean_anti_ai_text(text: str) -> str:
    """清洗 AI 输出中的反 AI 词 (V12.7: 跳过危险常用词 + 替换语去主语代词, 不破坏正常文本)"""
    import re
    result = text
    sorted_items = sorted(ANTI_AI_PHRASES.items(), key=lambda x: -len(x[0]))
    marker_to_good = {}
    marker_idx = 0
    for bad, good in sorted_items:
        if bad in _NEUTRALIZED_BAD:
            continue  # 危险常用词, 跳过不替换
        is_ascii = bad.isascii()
        if not good:
            if is_ascii:
                result = re.sub(re.escape(bad), " ", result, flags=re.IGNORECASE)
            else:
                result = result.replace(bad, " ")
            continue
        marker = chr(0xE000 + marker_idx)
        marker_idx += 1
        marker_to_good[marker] = good
        if is_ascii:
            result = re.sub(re.escape(bad), marker, result, flags=re.IGNORECASE)
        else:
            result = result.replace(bad, marker)
    if marker_to_good:
        marker_pattern = re.compile(r"([一-鿿])?([\uE000-\uF8FF])([一-鿿])?")
        def repl(m):
            prev = m.group(1) or ""
            mk = m.group(2)
            nxt = m.group(3) or ""
            g = marker_to_good.get(mk, mk)
            # V12.7: 替换语若以主语代词开头且前文已有主语, 去掉代词 (防"她他"病句)
            if prev and g and g[0] in "他她":
                g = g[1:]
            # 去粘字
            if prev and g and prev == g[0]:
                g = g[1:]
            if nxt and g and g[-1] == nxt:
                g = g[:-1]
            return prev + g + nxt
        result = marker_pattern.sub(repl, result)
    # V14.2 P0 修复: 移除"汉字间单空格压缩"规则。它会把固定列宽分镜表里"恰为 1 个空格"的
    #   填充吞掉 (如 6 字景别占 7 位列), 导致后置列整体错位、时长错读、总时长少算。
    #   场景驱动模板本就无 AI 套话可剥, 该规则在正文上是空转, 在结构化表格上是破坏 — 故删除。
    #   (标点旁的空格清理保留, 不影响列宽对齐。)
    result = re.sub(r"([，。！？、]) ", lambda m: m.group(1), result)
    result = re.sub(r" ([，。！？、])", lambda m: m.group(1), result)
    result = re.sub(r"([，。！？])\1+", lambda m: m.group(1), result)
    return result.strip()



