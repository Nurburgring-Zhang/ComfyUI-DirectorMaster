def get_director_profile(name):
    """查询导演档案 — 别名→精确→双向模糊(核心键优先, 变体键兜底)→代表作→中性通用.
    V13.4 修复: (1)最长键优先误选 (peers) 变体键 (Christopher Nolan→Tony Scott);
    (2)英文名经别名映射到核心中文键; (3)过短查询(<2字符)走兜底。"""
    if not name:
        return {}
    if name in DIRECTOR_PROFILES_ALL:
        return DIRECTOR_PROFILES_ALL[name]
    name_str = str(name).strip()
    # 别名映射 (英文名/常见变体 → 核心中文键)
    _norm = name_str.lower().replace(" ", "")
    if _norm in _DIRECTOR_ALIASES:
        _core = _DIRECTOR_ALIASES[_norm]
        if _core in DIRECTOR_PROFILES_ALL:
            return DIRECTOR_PROFILES_ALL[_core]
    # 过短查询保护 (单字 '安'/'兰'/'王' 不可靠)
    if len(name_str.replace(" ", "")) < 2:
        return {
            "镜头": "中景 + 自然光", "光": "自然光", "节奏": "中等", "色彩": "自然",
            "表演": "写实", "构图": "三分法", "声音": "环境音", "情绪": "中性",
            "代表作": "通用", "物件": "通用", "年代": "现代", "5维标签": "通用",
        }
    name_lower = name_str.lower().replace(" ", "")
    # 双向子串匹配 — 核心键优先 (不含变体标记), 最长键优先; 无核心匹配才用变体键
    best_core, best_core_len = None, 0
    best_var, best_var_len = None, 0
    for k, v in DIRECTOR_PROFILES_ALL.items():
        k_lower = k.lower().replace(" ", "")
        if name_lower in k_lower or k_lower in name_lower:
            if _is_variant_key(k):
                if len(k_lower) > best_var_len:
                    best_var, best_var_len = k, len(k_lower)
            else:
                if len(k_lower) > best_core_len:
                    best_core, best_core_len = k, len(k_lower)
    if best_core:
        return DIRECTOR_PROFILES_ALL[best_core]
    if best_var:
        return DIRECTOR_PROFILES_ALL[best_var]
    # 代表作匹配兜底
    for k, v in DIRECTOR_PROFILES_ALL.items():
        if name_lower in str(v.get("代表作", "")).lower():
            return v
    # 无匹配 → 中性通用档案 (不再硬编码王家卫)
    return {
        "镜头": "中景 + 自然光", "光": "自然光", "节奏": "中等", "色彩": "自然",
        "表演": "写实", "构图": "三分法", "声音": "环境音", "情绪": "中性",
        "代表作": "通用", "物件": "通用", "年代": "现代", "5维标签": "通用",
    }


