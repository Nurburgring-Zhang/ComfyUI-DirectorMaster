def apply_dimensions(node_type, kwargs):
    """读取维度选择, 返回格式化的维度生效块 (确保每个下拉都真实影响输出)."""
    lines = ["【维度配置(已生效)】"]
    if node_type == "剧本":
        struct = kwargs.get("叙事结构", "三幕剧")
        dial = kwargs.get("对白密度", "极简")
        subtext = kwargs.get("潜文本强度", "强")
        rhythm = kwargs.get("节奏控制", "慢")
        depth = kwargs.get("主题深度", "深")
        lines.append(f"  叙事结构: {struct} → 场次按{struct}组织")
        lines.append(f"  对白密度: {dial} → 对白字数控制")
        lines.append(f"  潜文本强度: {subtext} → 每句对白下潜藏{subtext}潜文本")
        lines.append(f"  节奏: {rhythm} → 场次长度/切镜频率按此")
        lines.append(f"  主题深度: {depth} → 哲学内核表达程度")
    elif node_type == "创意":
        direction = kwargs.get("创意方向", "作者电影")
        world = kwargs.get("世界观深度", "中")
        emotion = kwargs.get("情感浓度", "克制")
        sell = kwargs.get("商业卖点", "有卖点")
        lines.append(f"  创意方向: {direction} → 概念/类型/受众按此定位")
        lines.append(f"  世界观深度: {world} → 世界设定详尽程度")
        lines.append(f"  情感浓度: {emotion} → 情感表达强度")
        lines.append(f"  商业卖点: {sell} → 商业逻辑/爆款要素")
    elif node_type == "美术":
        color = kwargs.get("色彩风格", "梦幻")
        light = kwargs.get("光影方向", "逆光")
        material = kwargs.get("材质重点", "织物")
        comp = kwargs.get("构图法则", "三分法")
        photo = kwargs.get("摄影风格", "手持")
        lines.append(f"  色彩风格: {color} → 色彩系统: {COLOR_MAP.get(color, color)}")
        lines.append(f"  光影方向: {light} → 光影设计: {LIGHT_MAP.get(light, light)}")
        lines.append(f"  材质重点: {material} → 材质细节: {MATERIAL_MAP.get(material, material)}")
        lines.append(f"  构图法则: {comp} → 视觉构图: {comp}")
        lines.append(f"  摄影风格: {photo} → 运镜方式: {photo}")
    elif node_type == "声音":
        ss = kwargs.get("声音风格", "写实")
        ms = kwargs.get("音乐风格", "极简钢琴")
        rv = kwargs.get("混响空间", "中混响")
        dn = kwargs.get("声音密度", "适中")
        sr = kwargs.get("留白比例", 0.3)
        lines.append(f"  声音风格: {ss} → {SOUND_STYLE_MAP.get(ss, ss)}")
        lines.append(f"  音乐风格: {ms} → {MUSIC_MAP.get(ms, ms)}")
        lines.append(f"  混响空间: {rv} → {REVERB_MAP.get(rv, rv)}")
        lines.append(f"  声音密度: {dn} → 声音元素数量按此控制")
        lines.append(f"  留白比例: {sr} → 沉默层占总时长{sr*100:.0f}%")
    elif node_type == "分镜":
        size_pref = kwargs.get("景别偏好", "中景为主")
        move_pref = kwargs.get("运镜风格", "固定为主")
        focal_pref = kwargs.get("焦段偏好", "标准35-50mm")
        comp_pref = kwargs.get("构图法则", "三分法")
        rhythm_pref = kwargs.get("剪辑节奏", "慢")
        lines.append(f"  景别偏好: {size_pref} → 镜头景别按此分配")
        lines.append(f"  运镜风格: {move_pref} → {MOVE_MAP.get(move_pref, move_pref)}")
        lines.append(f"  焦段偏好: {focal_pref} → 镜头焦段按此选择")
        lines.append(f"  构图法则: {comp_pref} → 每镜构图按此")
        lines.append(f"  剪辑节奏: {rhythm_pref} → 切镜频率/时长按此")
    return "\n".join(lines)
