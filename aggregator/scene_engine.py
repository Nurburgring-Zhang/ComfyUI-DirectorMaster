def _kw_hits_valid(desc, kw):
    """kw 在 desc 中是否存在有效命中 (单字词需避开复合词屏蔽窗口)."""
    start = desc.find(kw)
    if start < 0:
        return False
    if len(kw) > 1:
        return True
    blocks = _SINGLE_KW_BLOCK_WINDOWS.get(kw)
    if not blocks:
        return True
    pos = start
    while pos >= 0:
        win2 = {desc[pos - 1:pos + 1], desc[pos:pos + 2]}
        win3 = {desc[pos - 2:pos + 1], desc[pos - 1:pos + 2], desc[pos:pos + 3]}
        if not any(b in win2 or b in win3 for b in blocks):
            return True
        pos = desc.find(kw, pos + 1)
    return False


