def get_stage_variant(stage, seed_key):
    """从阶段变体池确定性选择1个 (同输入→同输出, 不同输入→不同变体)."""
    pool = STORY_STAGES_POOL.get(stage, [STORY_STAGES.get(stage, STORY_STAGES["建立"])])
    return _pick(seed_key, pool)


def get_stage_for_shot(shot_index, total_shots, num_stages=None):
    """V12.6 v13: 根据镜头序号映射到故事阶段 (默认 8 阶段, 兼容 5 阶段老调用).
    8 阶段均匀分配: 序章(0-1) → 建立(2-3) → 铺垫(4-5) → 中点(6) → 转折(7) → 高潮(8) → 留白(9) → 收束(10) → 主题升华(11+)
    """
    if total_shots <= 0:
        return "建立"
    if num_stages is None:
        num_stages = len(STAGE_ORDER)  # V12.6 v13: 默认 9 阶段 (含序章+主题升华)
    stage_idx = min(int(shot_index * num_stages / total_shots), num_stages - 1)
    return STAGE_ORDER[stage_idx]


