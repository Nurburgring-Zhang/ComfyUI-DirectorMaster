# 多方案池 — 每阶段多变体, 基于输入hash确定性选择
# 同输入→同输出(可复现), 不同输入→不同变体(泛化)
# ============================================================
import hashlib as _hashlib

def _pick(key, pool):
    """基于key的hash确定性选择 (同key→同选择, 不同key→不同选择)."""
    if not pool:
        return None
    return pool[int(_hashlib.md5(key.encode()).hexdigest(), 16) % len(pool)]

