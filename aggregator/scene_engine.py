def detect_story_line_type(scene_type, total_shots=6):
    """根据场景类型 + 镜头数 推荐故事线类型 (匹配类型, 不随意)."""
    for lt, info in STORY_LINE_TYPES.items():
        if scene_type in info["适合"] and total_shots <= info["max_shots"]:
            return lt
    return "单线"


