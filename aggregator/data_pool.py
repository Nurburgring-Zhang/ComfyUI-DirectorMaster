for mood in ["悲伤","悬疑","希望","史诗","浪漫","宁静","怀旧","愤怒"]:
    if mood not in MICRO_EXPR_POOL:
        MICRO_EXPR_POOL[mood] = MICRO_EXPR_POOL.get("孤独", MICRO_EXPR_POOL.get("温暖", {}))

def get_micro_expr(mood, category, seed_key, count=3):
    """从微表情数据库确定性选择count条."""
    pool = MICRO_EXPR_POOL.get(mood, MICRO_EXPR_POOL.get("孤独", {}))
    items = pool.get(category, [])
    if not items:
        return []
    # 确定性选择count条 (不重复)
    result = []
    used = set()
    for i in range(count):
        k = f"{seed_key}_{category}_{i}"
        idx = int(_hashlib.md5(k.encode()).hexdigest(), 16) % len(items)
        # 找未用的
        attempts = 0
        while idx in used and attempts < len(items):
            idx = (idx + 1) % len(items)
            attempts += 1
        used.add(idx)
        if idx < len(items):
            result.append(items[idx])
    return result


