"""
aggregator/data_pool.py — 全数据库扩充引擎
=============================================
所有数据库按类型×维度拆解, 多方案确定性随机组合, 增加泛化.
原则: 主流输出符合大众审美, 只有指定特殊数据时才组合特殊要求.
一致性: 同剧本内服化道一致性高, 不同剧本差异大.

数据库清单:
  1. DIALOGUE_POOL  — 对白数据库 (情绪×场景类型, 每组合3+变体)
  2. MICRO_EXPR_POOL — 微表情数据库 (10情绪×6类, 每类10+条)
  3. COSTUME_POOL   — 服装实物数据库 (时代×风格, 含一致性控制)
  4. SCENE_BLOCK_POOL — 场景调度数据库 (场景类型×布局, 3变体)
  5. TRANSITION_POOL  — 转场方案数据库 (阶段×场景类型, 5+方案)
  6. SHOT_STRATEGY_POOL — 多套镜头策略 (每类型3套)
  7. AMBIENT_SOUND_POOL — 环境音数据库 (场景类型×时段, 5+条)
"""
import hashlib as _hashlib

def _pick(key, pool):
    """确定性选择 (同key→同输出, 不同key→不同输出)."""
    if not pool:
        return None
    return pool[int(_hashlib.md5(key.encode()).hexdigest(), 16) % len(pool)]


