# 微调 Prompt 模板 — 把真实剧本范式注入 LLM
# ============================================================

def build_micro_finetune_prompt(director: str, scene_type: str = "人物对白") -> str:
    """根据导演 + 场景类型构建微调 prompt"""
    if director not in ALL_DIRECTORS:
        return ""
    d = ALL_DIRECTORS[director]
    name = d["name"]
    sig_phrases = chr(10).join("  " + p for p in d["signature_phrases"])
    sig_moments = chr(10).join("  • " + m for m in d["signature_moments"])
    visual = chr(10).join("  • " + v for v in d["visual_directives"])
    emotion = chr(10).join("  • " + e for e in d["emotional_grammar"])
    anti_ai_lines = []
    for a in d["anti_ai_lessons"]:
        if "✗" in a:
            parts = a.split("✗", 1)
            anti_ai_lines.append("  ✗ " + parts[0].strip())
            if "✓" in parts[1]:
                p2 = parts[1].split("✓", 1)
                anti_ai_lines.append("  ✓ " + p2[1].strip())
        else:
            anti_ai_lines.append("  " + a)
    anti_ai_text = chr(10).join(anti_ai_lines)
    directive = d["key_directive"]
    return f"""【用{name}的方式写{scene_type}】

【{name}标志性句式范本(对白样本,真实出处)】
{sig_phrases}

【{name}标志性场景(真实出处)】
{sig_moments}

【{name}镜头语言习惯】
{visual}

【{name}情感表达方式】
{emotion}

【{name}反 AI 教训 — 不要这样写, 应该这样写】
{anti_ai_text}

【{name}的导演信条】
  {directive}

【写作要求 — 严格遵守】
1. 不要解释情绪, 用{name}的方式呈现
2. 标志性句式里学{name}的对白节奏
3. 镜头语言按{name}的视觉习惯
4. 不要用反 AI 词表里的任何词
5. 让{name}的真实剧本范本决定你的语气
"""


